import { parse as parseYaml } from "yaml";
import { discoverSkills } from "./discover.ts";
import { mergeProvenance, type IndexedSkill } from "./provenance.ts";

export interface StartRule {
  when: string;
  use: string;
}

export interface Flow {
  id: string;
  title: string;
  steps: string[];
}

export interface Capability {
  title: string;
  openspec?: string;
  plain?: string;
}

export interface Catalog {
  id: string;
  title: string;
  description?: string;
  skills: string[];
}

export interface Taxonomy {
  intro?: string;
  start: StartRule[];
  flows: Flow[];
  capabilities: Capability[];
  catalog: Catalog[];
}

export interface BuildOptions {
  roots: string[];
  lockfile: unknown;
  taxonomy: string;
}

export interface BuildResult {
  index: IndexedSkill[];
  markdown: string;
  unplaced: string[];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function str(value: unknown): string | undefined {
  return typeof value === "string" ? value : undefined;
}

function strList(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((v): v is string => typeof v === "string") : [];
}

export function parseTaxonomy(source: string): Taxonomy {
  const parsed = parseYaml(source);
  if (!isRecord(parsed)) {
    return { start: [], flows: [], capabilities: [], catalog: [] };
  }

  const start = Array.isArray(parsed["start"])
    ? parsed["start"].flatMap((entry): StartRule[] => {
        if (!isRecord(entry)) return [];
        const when = str(entry["when"]);
        const use = str(entry["use"]);
        return when && use ? [{ when, use }] : [];
      })
    : [];

  const flows = Array.isArray(parsed["flows"])
    ? parsed["flows"].flatMap((entry): Flow[] => {
        if (!isRecord(entry)) return [];
        const id = str(entry["id"]);
        if (!id) return [];
        return [{ id, title: str(entry["title"]) ?? id, steps: strList(entry["steps"]) }];
      })
    : [];

  const capabilities = Array.isArray(parsed["capabilities"])
    ? parsed["capabilities"].flatMap((entry): Capability[] => {
        if (!isRecord(entry)) return [];
        const title = str(entry["title"]);
        if (!title) return [];
        return [{ title, openspec: str(entry["openspec"]), plain: str(entry["plain"]) }];
      })
    : [];

  const catalog = Array.isArray(parsed["catalog"])
    ? parsed["catalog"].flatMap((entry): Catalog[] => {
        if (!isRecord(entry)) return [];
        const title = str(entry["title"]);
        if (!title) return [];
        return [
          {
            id: str(entry["id"]) ?? title,
            title,
            description: str(entry["description"]),
            skills: strList(entry["skills"]),
          },
        ];
      })
    : [];

  return { intro: str(parsed["intro"]), start, flows, capabilities, catalog };
}

/**
 * Names referenced by a slash command in prose. `/opsx:propose` is the same
 * skill as `openspec-propose`, so normalize the two spellings together.
 */
function skillNameFromCommand(token: string): string {
  return token.startsWith("opsx:") ? `openspec-${token.slice("opsx:".length)}` : token;
}

function collectReferencedNames(text: string): string[] {
  const names: string[] = [];
  for (const match of text.matchAll(/\/([A-Za-z0-9][A-Za-z0-9:_.-]*)/g)) {
    names.push(skillNameFromCommand(match[1]!));
  }
  return names;
}

/**
 * The skill name a catalog line claims to place: the text before the first
 * ` - ` separator, e.g. "wrangler - deploy to Cloudflare" places `wrangler`.
 */
function catalogName(line: string): string {
  return line.split(" - ")[0]!.trim();
}

export function placedNames(taxonomy: Taxonomy): Set<string> {
  const placed = new Set<string>();
  for (const flow of taxonomy.flows) {
    for (const step of flow.steps) {
      for (const name of collectReferencedNames(step)) placed.add(name);
    }
  }
  for (const capability of taxonomy.capabilities) {
    for (const value of [capability.openspec, capability.plain]) {
      if (value) for (const name of collectReferencedNames(value)) placed.add(name);
    }
  }
  for (const group of taxonomy.catalog) {
    for (const line of group.skills) {
      placed.add(catalogName(line));
      for (const name of collectReferencedNames(line)) placed.add(name);
    }
  }
  return placed;
}

function skillLine(skill: IndexedSkill): string {
  const source = skill.provenance?.source;
  return `- **${skill.name}**: ${skill.description}${source ? ` _(${source})_` : ""}`;
}

export function renderRouter(
  index: IndexedSkill[],
  taxonomy: Taxonomy,
  unplaced: IndexedSkill[],
): string {
  const lines: string[] = ["# Skill Router", ""];
  lines.push("_Generated by skill-index. Do not edit by hand; edit `taxonomy.yml` instead._", "");

  if (taxonomy.intro) {
    lines.push(taxonomy.intro, "");
  }

  if (taxonomy.start.length > 0) {
    lines.push("## Start here", "");
    for (const rule of taxonomy.start) {
      lines.push(`- ${rule.when} -> **${rule.use}**`);
    }
    lines.push("");
  }

  for (const flow of taxonomy.flows) {
    lines.push(`## ${flow.title}`, "");
    flow.steps.forEach((step, i) => lines.push(`${i + 1}. ${step}`));
    lines.push("");
  }

  if (taxonomy.capabilities.length > 0) {
    lines.push("## Capability map", "");
    lines.push("| Capability | OpenSpec repo | Plain repo |");
    lines.push("| --- | --- | --- |");
    for (const cap of taxonomy.capabilities) {
      lines.push(`| ${cap.title} | ${cap.openspec ?? "-"} | ${cap.plain ?? "-"} |`);
    }
    lines.push("");
  }

  for (const group of taxonomy.catalog) {
    lines.push(`## ${group.title}`, "");
    if (group.description) {
      lines.push(group.description, "");
    }
    for (const line of group.skills) {
      lines.push(`- ${line}`);
    }
    lines.push("");
  }

  if (unplaced.length > 0) {
    lines.push("## Unplaced", "");
    lines.push(
      "These skills are not in `taxonomy.yml`, so nothing tells you when to reach for them. Add each to a `catalog` group or a flow.",
      "",
    );
    for (const skill of unplaced) {
      lines.push(skillLine(skill));
    }
    lines.push("");
  }

  lines.push(`## All indexed skills (${index.length})`, "");
  for (const skill of index) {
    lines.push(skillLine(skill));
  }
  lines.push("");

  return lines.join("\n");
}

export function buildIndex(options: BuildOptions): BuildResult {
  const skills = discoverSkills(options.roots);
  const index = mergeProvenance(skills, options.lockfile);
  const taxonomy = parseTaxonomy(options.taxonomy);
  const placed = placedNames(taxonomy);
  const unplaced = index.filter((skill) => !placed.has(skill.name));
  const markdown = renderRouter(index, taxonomy, unplaced);
  return { index, markdown, unplaced: unplaced.map((skill) => skill.name) };
}
